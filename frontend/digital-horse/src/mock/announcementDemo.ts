/**
 * 根据输入文本生成正式公告文。
 *
 * 真实对接后端 LLM 时，把这个函数体替换为：
 *   const { data } = await axios.post('/api/v1/announcements/draft', { input, audience, channel, issuer });
 *   return data.text;
 *
 * 设计要点：
 *   - 把口播/会议结论重新组装为公文体：标题 → 引言 → 正文（编号） → 要求 → 落款
 *   - 不引入输入中没有的新事实，不擅自补全金额 / 日期 / 人名
 *   - 输出纯文本，不带 # ** _ —— 等 AI 风格标记
 *   - 给出"润色说明"，方便演示者讲解 AI 做了什么
 */
export function draftAnnouncement(opts: {
  input: string;
  audience: string;
  channel: string;
  issuer: string;
}): { text: string; rationale: string } {
  const { input, audience, channel, issuer } = opts;

  // 演示版：根据输入 id 匹配预设公告（更可控）
  const preset = ANNOUNCEMENT_PRESETS.find((p) => p.matchesInput === input || p.id === 'preset-compliance');

  if (preset) {
    return { text: preset.text, rationale: preset.rationale };
  }

  // 兜底：通用模板
  return {
    text: `关于推进相关工作的通知

${audience}：

${input}

特此通知，请遵照执行。

${issuer}
${new Date().toLocaleDateString('zh-CN', { year: 'numeric', month: 'long', day: 'numeric' })}`,
    rationale: '已按公文体重新梳理：合并重复表述、补全落款与日期。',
  };
}

