export function getRegulationById(id: string): Regulation | undefined {
  return REGULATIONS.find((r) => r.id === id);
}

export function getRegulationsByIds(ids: string[]): Regulation[] {
  return ids.map((id) => getRegulationById(id)).filter(Boolean) as Regulation[];
}

export function searchRegulations(keyword: string): Regulation[] {
  if (!keyword.trim()) return REGULATIONS;
  const kw = keyword.toLowerCase();
  return REGULATIONS.filter(
    (r) =>
      r.shortName.toLowerCase().includes(kw) ||
      r.fullName.toLowerCase().includes(kw) ||
      r.articleText.toLowerCase().includes(kw) ||
      r.article.toLowerCase().includes(kw)
  );
}
